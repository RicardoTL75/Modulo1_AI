# Arithmetic operations with integers
a = 5
b = 10

print("Integers:")
print("a - b =", a - b, ", type:", type(a - b))
print("a + b =", a + b, ", type:", type(a + b))
print("a * b =", a * b, ", type:", type(a * b))
print("b / a =", b / a, ", type:", type(b / a))   # always float


# Arithmetic operations with floats
x = 5.0
y = 10.0
print("\n\nOperations x = 5.0; y = 10.0")

print("\nFloats:")
print("x - y =", x - y, ", type:", type(x - y))
print("x + y =", x + y, ", type:", type(x + y))
print("x * y =", x * y, ", type:", type(x * y))
print("x / y =", x / y, ", type:", type(x / y))


# Arithmetic operations with integers vs floats
c = 4
z = 0.5
print("\n\nOperations c = 4; z = 0.5")

print("\nIntegers vs Floats:")
print("c + z =", c + z, ", type:", type(c + z))
print("c - z =", c - z, ", type:", type(c - z))
print("c * z =", c * z, ", type:", type(c * z))
print("c / z =", c / z, ", type:", type(c / z))
